create or replace function public.get_cup_manager_gameweek_score(
  p_league_id uuid,
  p_user_id uuid,
  p_gameweek integer
)
returns table(
  total_score integer,
  fpl_points integer,
  defcon_points integer,
  highest_starter integer,
  goals integer,
  assists integer
)
language sql
stable
security definer
set search_path = ''
as $$
  with selected_players as (
    select selected.player_id
    from public.gameweek_lineup_snapshots snapshot
    cross join lateral pg_catalog.unnest(snapshot.effective_starting_player_ids) selected(player_id)
    where snapshot.league_id = p_league_id
      and snapshot.user_id = p_user_id
      and snapshot.gameweek = p_gameweek

    union all

    select roster.player_id
    from public.rosters roster
    where roster.league_id = p_league_id
      and roster.user_id = p_user_id
      and roster.is_starting
      and not exists (
        select 1 from public.gameweek_lineup_snapshots snapshot
        where snapshot.league_id = p_league_id
          and snapshot.user_id = p_user_id
          and snapshot.gameweek = p_gameweek
      )
  ), player_scores as (
    select
      coalesce(stats.total_points, 0)::integer as fpl_points,
      public.calculate_player_defcon_points(
        p_league_id,
        player.element_type::text,
        coalesce(stats.defensive_contribution, 0)::integer
      )::integer as defcon_points,
      coalesce(stats.goals_scored, 0)::integer as goals,
      coalesce(stats.assists, 0)::integer as assists
    from selected_players selected
    join public.players player on player.id = selected.player_id
    left join public.player_gameweek_stats stats
      on stats.player_id = selected.player_id and stats.gameweek = p_gameweek
  )
  select
    coalesce(pg_catalog.sum(score.fpl_points + score.defcon_points), 0)::integer,
    coalesce(pg_catalog.sum(score.fpl_points), 0)::integer,
    coalesce(pg_catalog.sum(score.defcon_points), 0)::integer,
    coalesce(pg_catalog.max(score.fpl_points + score.defcon_points), 0)::integer,
    coalesce(pg_catalog.sum(score.goals), 0)::integer,
    coalesce(pg_catalog.sum(score.assists), 0)::integer
  from player_scores score;
$$;

revoke all on function public.get_cup_manager_gameweek_score(uuid, uuid, integer)
  from public, anon, authenticated;
grant execute on function public.get_cup_manager_gameweek_score(uuid, uuid, integer)
  to service_role;

create or replace function public.create_single_knockout_cup(
  p_league_id uuid,
  p_name text,
  p_start_gameweek integer,
  p_participant_ids uuid[] default null,
  p_tie_breakers text[] default array[
    'HIGHEST_STARTER', 'MOST_GOALS', 'MOST_ASSISTS', 'HIGHER_SEED'
  ]::text[]
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_name text := nullif(pg_catalog.btrim(coalesce(p_name, '')), '');
  v_cup_id uuid := pg_catalog.gen_random_uuid();
  v_participants uuid[];
  v_participant_count integer;
  v_bracket_size integer := 1;
  v_round_count integer := 0;
  v_round_number integer;
  v_round_size integer;
  v_round_name text;
  v_round_id uuid;
  v_opening_matches integer;
  v_contested_matches integer;
  v_match integer;
  v_home_seed integer;
  v_away_seed integer;
  v_home_user uuid;
  v_away_user uuid;
  v_allowed_breakers constant text[] := array[
    'HIGHEST_STARTER', 'MOST_GOALS', 'MOST_ASSISTS', 'HIGHER_SEED'
  ]::text[];
begin
  if v_user_id is null then
    return jsonb_build_object('success', false, 'error', 'AUTH_REQUIRED');
  end if;

  if not exists (
    select 1 from public.leagues league
    where league.id = p_league_id and league.commissioner_id = v_user_id
  ) then
    return jsonb_build_object('success', false, 'error', 'COMMISSIONER_REQUIRED');
  end if;

  if v_name is null or pg_catalog.char_length(v_name) > 60 then
    return jsonb_build_object('success', false, 'error', 'INVALID_CUP_NAME');
  end if;

  if p_start_gameweek is null or p_start_gameweek not between 1 and 38 then
    return jsonb_build_object('success', false, 'error', 'INVALID_START_GAMEWEEK');
  end if;

  if p_tie_breakers is null
     or pg_catalog.cardinality(p_tie_breakers) <> pg_catalog.cardinality(v_allowed_breakers)
     or p_tie_breakers @> v_allowed_breakers is false
     or v_allowed_breakers @> p_tie_breakers is false then
    return jsonb_build_object('success', false, 'error', 'INVALID_TIE_BREAKERS');
  end if;

  select pg_catalog.array_agg(member.user_id order by member.user_id)
  into v_participants
  from public.league_members member
  where member.league_id = p_league_id
    and (
      p_participant_ids is null
      or member.user_id = any(p_participant_ids)
    );

  v_participant_count := coalesce(pg_catalog.cardinality(v_participants), 0);
  if v_participant_count < 2 then
    return jsonb_build_object('success', false, 'error', 'INSUFFICIENT_PARTICIPANTS');
  end if;

  if p_participant_ids is not null
     and v_participant_count <> pg_catalog.cardinality(p_participant_ids) then
    return jsonb_build_object('success', false, 'error', 'INVALID_PARTICIPANT');
  end if;

  while v_bracket_size < v_participant_count loop
    v_bracket_size := v_bracket_size * 2;
    v_round_count := v_round_count + 1;
  end loop;

  if p_start_gameweek + v_round_count - 1 > 38 then
    return jsonb_build_object('success', false, 'error', 'SCHEDULE_EXCEEDS_SEASON');
  end if;

  if exists (
    select 1 from public.cups cup
    where cup.league_id = p_league_id
      and pg_catalog.lower(cup.name) = pg_catalog.lower(v_name)
  ) then
    return jsonb_build_object('success', false, 'error', 'CUP_NAME_TAKEN');
  end if;

  insert into public.cups (
    id, league_id, name, start_gameweek, round_count, participant_count,
    seeding_method, tie_breakers, created_by
  ) values (
    v_cup_id, p_league_id, v_name, p_start_gameweek, v_round_count,
    v_participant_count, 'RANDOM', p_tie_breakers, v_user_id
  );

  insert into public.cup_entries (cup_id, league_id, user_id, seed)
  select
    v_cup_id,
    p_league_id,
    participant.user_id,
    row_number() over (
      order by pg_catalog.md5(participant.user_id::text || v_cup_id::text)
    )::integer
  from pg_catalog.unnest(v_participants) participant(user_id);

  for v_round_number in 1..v_round_count loop
    v_round_size := v_bracket_size / pg_catalog.power(2, v_round_number - 1)::integer;
    v_round_name := case
      when v_round_size = 2 then 'FINAL'
      when v_round_size = 4 then 'SEMI-FINALS'
      when v_round_size = 8 then 'QUARTER-FINALS'
      else 'ROUND OF ' || v_round_size::text
    end;

    insert into public.cup_rounds (
      cup_id, league_id, round_number, name, gameweek
    ) values (
      v_cup_id, p_league_id, v_round_number, v_round_name,
      p_start_gameweek + v_round_number - 1
    );
  end loop;

  select round.id into v_round_id
  from public.cup_rounds round
  where round.cup_id = v_cup_id and round.round_number = 1;

  v_opening_matches := v_bracket_size / 2;
  v_contested_matches := v_participant_count - v_opening_matches;

  for v_match in 1..v_opening_matches loop
    if v_match <= v_contested_matches then
      v_home_seed := ((v_match - 1) * 2) + 1;
      v_away_seed := v_home_seed + 1;
    else
      v_home_seed := (v_contested_matches * 2) + (v_match - v_contested_matches);
      v_away_seed := null;
    end if;

    select entry.user_id into v_home_user
    from public.cup_entries entry
    where entry.cup_id = v_cup_id and entry.seed = v_home_seed;

    v_away_user := null;
    if v_away_seed is not null then
      select entry.user_id into v_away_user
      from public.cup_entries entry
      where entry.cup_id = v_cup_id and entry.seed = v_away_seed;
    end if;

    insert into public.cup_fixtures (
      cup_id, league_id, round_id, round_number, match_number, gameweek,
      home_user_id, away_user_id, winner_user_id, status, resolution, finished_at
    ) values (
      v_cup_id, p_league_id, v_round_id, 1, v_match, p_start_gameweek,
      v_home_user, v_away_user,
      case when v_away_user is null then v_home_user else null end,
      case when v_away_user is null then 'BYE' else 'SCHEDULED' end,
      case when v_away_user is null then 'BYE' else null end,
      case when v_away_user is null then pg_catalog.now() else null end
    );
  end loop;

  insert into public.cup_audit_log (cup_id, league_id, action, actor_id, details)
  values (
    v_cup_id, p_league_id, 'CUP_CREATED', v_user_id,
    jsonb_build_object(
      'participants', v_participant_count,
      'rounds', v_round_count,
      'start_gameweek', p_start_gameweek,
      'seeding', 'RANDOM'
    )
  );

  return jsonb_build_object(
    'success', true,
    'cup_id', v_cup_id,
    'participants', v_participant_count,
    'rounds', v_round_count,
    'final_gameweek', p_start_gameweek + v_round_count - 1
  );
exception when unique_violation then
  return jsonb_build_object('success', false, 'error', 'CUP_NAME_TAKEN');
end;
$$;

revoke all on function public.create_single_knockout_cup(uuid, text, integer, uuid[], text[])
  from public, anon;
grant execute on function public.create_single_knockout_cup(uuid, text, integer, uuid[], text[])
  to authenticated, service_role;

create or replace function public.finalize_cup_gameweek(p_gameweek integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fixture record;
  v_round record;
  v_home record;
  v_away record;
  v_breaker text;
  v_winner uuid;
  v_loser uuid;
  v_resolution text;
  v_home_seed integer;
  v_away_seed integer;
  v_winners uuid[];
  v_next_round_id uuid;
  v_index integer;
  v_updated integer := 0;
  v_completed_cups integer := 0;
begin
  if not exists (
    select 1 from public.gameweeks gameweek
    where gameweek.gameweek_number = p_gameweek
      and coalesce(gameweek.is_finished, false)
  ) then
    return jsonb_build_object('success', false, 'error', 'GAMEWEEK_NOT_FINISHED');
  end if;

  for v_fixture in
    select fixture.*, cup.tie_breakers
    from public.cup_fixtures fixture
    join public.cups cup on cup.id = fixture.cup_id
    where fixture.gameweek = p_gameweek
      and fixture.status in ('SCHEDULED', 'LIVE')
      and fixture.home_user_id is not null
      and fixture.away_user_id is not null
    order by fixture.cup_id, fixture.round_number, fixture.match_number
    for update of fixture skip locked
  loop
    select * into v_home
    from public.get_cup_manager_gameweek_score(
      v_fixture.league_id, v_fixture.home_user_id, p_gameweek
    );
    select * into v_away
    from public.get_cup_manager_gameweek_score(
      v_fixture.league_id, v_fixture.away_user_id, p_gameweek
    );

    v_winner := null;
    v_resolution := 'TOTAL_SCORE';
    if v_home.total_score > v_away.total_score then
      v_winner := v_fixture.home_user_id;
    elsif v_away.total_score > v_home.total_score then
      v_winner := v_fixture.away_user_id;
    else
      foreach v_breaker in array v_fixture.tie_breakers loop
        if v_breaker = 'HIGHEST_STARTER' and v_home.highest_starter <> v_away.highest_starter then
          v_winner := case when v_home.highest_starter > v_away.highest_starter
            then v_fixture.home_user_id else v_fixture.away_user_id end;
        elsif v_breaker = 'MOST_GOALS' and v_home.goals <> v_away.goals then
          v_winner := case when v_home.goals > v_away.goals
            then v_fixture.home_user_id else v_fixture.away_user_id end;
        elsif v_breaker = 'MOST_ASSISTS' and v_home.assists <> v_away.assists then
          v_winner := case when v_home.assists > v_away.assists
            then v_fixture.home_user_id else v_fixture.away_user_id end;
        elsif v_breaker = 'HIGHER_SEED' then
          select entry.seed into v_home_seed from public.cup_entries entry
          where entry.cup_id = v_fixture.cup_id and entry.user_id = v_fixture.home_user_id;
          select entry.seed into v_away_seed from public.cup_entries entry
          where entry.cup_id = v_fixture.cup_id and entry.user_id = v_fixture.away_user_id;
          v_winner := case when v_home_seed < v_away_seed
            then v_fixture.home_user_id else v_fixture.away_user_id end;
        end if;

        if v_winner is not null then
          v_resolution := v_breaker;
          exit;
        end if;
      end loop;
    end if;

    if v_winner is null then
      raise exception 'Cup fixture % could not be resolved', v_fixture.id;
    end if;

    v_loser := case when v_winner = v_fixture.home_user_id
      then v_fixture.away_user_id else v_fixture.home_user_id end;

    update public.cup_fixtures fixture
    set home_score = v_home.total_score,
        away_score = v_away.total_score,
        winner_user_id = v_winner,
        status = 'COMPLETED',
        resolution = v_resolution,
        finished_at = pg_catalog.now()
    where fixture.id = v_fixture.id;

    update public.cup_entries entry
    set status = 'ELIMINATED', eliminated_round = v_fixture.round_number
    where entry.cup_id = v_fixture.cup_id and entry.user_id = v_loser;

    insert into public.cup_audit_log (cup_id, league_id, action, details)
    values (
      v_fixture.cup_id, v_fixture.league_id, 'FIXTURE_FINALIZED',
      jsonb_build_object(
        'fixture_id', v_fixture.id,
        'gameweek', p_gameweek,
        'home_score', v_home.total_score,
        'away_score', v_away.total_score,
        'winner_user_id', v_winner,
        'resolution', v_resolution
      )
    );
    v_updated := v_updated + 1;
  end loop;

  for v_round in
    select round.*
    from public.cup_rounds round
    join public.cups cup on cup.id = round.cup_id
    where round.gameweek = p_gameweek
      and round.status <> 'COMPLETED'
      and not exists (
        select 1 from public.cup_fixtures fixture
        where fixture.round_id = round.id
          and fixture.status not in ('COMPLETED', 'BYE')
      )
    order by round.cup_id, round.round_number
    for update of round
  loop
    update public.cup_rounds round
    set status = 'COMPLETED'
    where round.id = v_round.id;

    if v_round.round_number = (
      select cup.round_count from public.cups cup where cup.id = v_round.cup_id
    ) then
      select fixture.winner_user_id,
             case when fixture.winner_user_id = fixture.home_user_id
               then fixture.away_user_id else fixture.home_user_id end
      into v_winner, v_loser
      from public.cup_fixtures fixture
      where fixture.round_id = v_round.id
      order by fixture.match_number
      limit 1;

      update public.cups cup
      set status = 'COMPLETED', champion_user_id = v_winner,
          runner_up_user_id = v_loser, updated_at = pg_catalog.now()
      where cup.id = v_round.cup_id;
      update public.cup_entries entry
      set status = 'CHAMPION'
      where entry.cup_id = v_round.cup_id and entry.user_id = v_winner;
      insert into public.cup_audit_log (cup_id, league_id, action, details)
      values (
        v_round.cup_id, v_round.league_id, 'CUP_COMPLETED',
        jsonb_build_object('champion_user_id', v_winner, 'runner_up_user_id', v_loser)
      );
      v_completed_cups := v_completed_cups + 1;
    else
      select pg_catalog.array_agg(fixture.winner_user_id order by fixture.match_number)
      into v_winners
      from public.cup_fixtures fixture
      where fixture.round_id = v_round.id;

      select round.id into v_next_round_id
      from public.cup_rounds round
      where round.cup_id = v_round.cup_id
        and round.round_number = v_round.round_number + 1;

      for v_index in 1..(pg_catalog.cardinality(v_winners) / 2) loop
        insert into public.cup_fixtures (
          cup_id, league_id, round_id, round_number, match_number, gameweek,
          home_user_id, away_user_id, status
        ) values (
          v_round.cup_id, v_round.league_id, v_next_round_id,
          v_round.round_number + 1, v_index, p_gameweek + 1,
          v_winners[((v_index - 1) * 2) + 1],
          v_winners[((v_index - 1) * 2) + 2],
          'SCHEDULED'
        )
        on conflict (round_id, match_number) do nothing;
      end loop;

      update public.cups cup
      set status = 'LIVE', updated_at = pg_catalog.now()
      where cup.id = v_round.cup_id and cup.status = 'SCHEDULED';
    end if;
  end loop;

  return jsonb_build_object(
    'success', true,
    'gameweek', p_gameweek,
    'fixtures_finalized', v_updated,
    'cups_completed', v_completed_cups
  );
end;
$$;

