create or replace function public.get_cup_fixture_board(p_league_id uuid)
returns table(
  cup_id uuid,
  cup_name text,
  cup_status text,
  round_id uuid,
  round_number integer,
  round_name text,
  gameweek integer,
  round_status text,
  fixture_id uuid,
  match_number integer,
  fixture_status text,
  home_user_id uuid,
  home_team_name text,
  home_score integer,
  home_fpl_points integer,
  home_defcon_points integer,
  away_user_id uuid,
  away_team_name text,
  away_score integer,
  away_fpl_points integer,
  away_defcon_points integer,
  winner_user_id uuid,
  resolution text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    cup.id,
    cup.name,
    cup.status,
    round.id,
    round.round_number,
    round.name,
    round.gameweek,
    round.status,
    fixture.id,
    fixture.match_number,
    fixture.status,
    fixture.home_user_id,
    coalesce(home_member.team_name, 'TBD'),
    case when fixture.status in ('COMPLETED', 'BYE')
      then coalesce(fixture.home_score, 0) else coalesce(home_live.total_score, 0) end,
    coalesce(home_live.fpl_points, 0),
    coalesce(home_live.defcon_points, 0),
    fixture.away_user_id,
    case when fixture.status = 'BYE' then 'BYE'
      else coalesce(away_member.team_name, 'TBD') end,
    case when fixture.status in ('COMPLETED', 'BYE')
      then coalesce(fixture.away_score, 0) else coalesce(away_live.total_score, 0) end,
    coalesce(away_live.fpl_points, 0),
    coalesce(away_live.defcon_points, 0),
    fixture.winner_user_id,
    fixture.resolution
  from public.cups cup
  join public.cup_rounds round on round.cup_id = cup.id
  left join public.cup_fixtures fixture on fixture.round_id = round.id
  left join public.league_members home_member
    on home_member.league_id = cup.league_id and home_member.user_id = fixture.home_user_id
  left join public.league_members away_member
    on away_member.league_id = cup.league_id and away_member.user_id = fixture.away_user_id
  left join lateral public.get_cup_manager_gameweek_score(
    cup.league_id, fixture.home_user_id, round.gameweek
  ) home_live on fixture.home_user_id is not null
  left join lateral public.get_cup_manager_gameweek_score(
    cup.league_id, fixture.away_user_id, round.gameweek
  ) away_live on fixture.away_user_id is not null
  where cup.league_id = p_league_id
    and exists (
      select 1 from public.league_members viewer
      where viewer.league_id = p_league_id and viewer.user_id = auth.uid()
    )
  order by cup.created_at desc, round.round_number, fixture.match_number;
$$;

