-- League cups V1: secure single-knockout creation, live scoring and
-- repeat-safe progression after official Gameweek finalization.

create table if not exists public.cups (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  league_id uuid not null references public.leagues(id) on delete cascade,
  name text not null check (pg_catalog.char_length(pg_catalog.btrim(name)) between 1 and 60),
  format text not null default 'SINGLE_KNOCKOUT'
    check (format in ('SINGLE_KNOCKOUT')),
  status text not null default 'SCHEDULED'
    check (status in ('SCHEDULED', 'LIVE', 'COMPLETED', 'CANCELLED')),
  start_gameweek integer not null check (start_gameweek between 1 and 38),
  round_count integer not null check (round_count between 1 and 6),
  participant_count integer not null check (participant_count between 2 and 64),
  seeding_method text not null default 'RANDOM' check (seeding_method in ('RANDOM')),
  tie_breakers text[] not null default array[
    'HIGHEST_STARTER', 'MOST_GOALS', 'MOST_ASSISTS', 'HIGHER_SEED'
  ]::text[],
  champion_user_id uuid references auth.users(id) on delete set null,
  runner_up_user_id uuid references auth.users(id) on delete set null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now(),
  unique (league_id, name)
);

create table if not exists public.cup_entries (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  cup_id uuid not null references public.cups(id) on delete cascade,
  league_id uuid not null references public.leagues(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  seed integer not null check (seed > 0),
  status text not null default 'ACTIVE'
    check (status in ('ACTIVE', 'ELIMINATED', 'CHAMPION')),
  eliminated_round integer,
  created_at timestamptz not null default pg_catalog.now(),
  unique (cup_id, user_id),
  unique (cup_id, seed)
);

create table if not exists public.cup_rounds (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  cup_id uuid not null references public.cups(id) on delete cascade,
  league_id uuid not null references public.leagues(id) on delete cascade,
  round_number integer not null check (round_number > 0),
  name text not null,
  gameweek integer not null check (gameweek between 1 and 38),
  status text not null default 'SCHEDULED'
    check (status in ('SCHEDULED', 'LIVE', 'COMPLETED')),
  created_at timestamptz not null default pg_catalog.now(),
  unique (cup_id, round_number),
  unique (cup_id, gameweek)
);

create table if not exists public.cup_fixtures (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  cup_id uuid not null references public.cups(id) on delete cascade,
  league_id uuid not null references public.leagues(id) on delete cascade,
  round_id uuid not null references public.cup_rounds(id) on delete cascade,
  round_number integer not null check (round_number > 0),
  match_number integer not null check (match_number > 0),
  gameweek integer not null check (gameweek between 1 and 38),
  home_user_id uuid references auth.users(id) on delete set null,
  away_user_id uuid references auth.users(id) on delete set null,
  home_score integer,
  away_score integer,
  winner_user_id uuid references auth.users(id) on delete set null,
  status text not null default 'SCHEDULED'
    check (status in ('SCHEDULED', 'LIVE', 'COMPLETED', 'BYE')),
  resolution text,
  finished_at timestamptz,
  created_at timestamptz not null default pg_catalog.now(),
  unique (round_id, match_number),
  check (home_user_id is null or away_user_id is null or home_user_id <> away_user_id)
);

create table if not exists public.cup_audit_log (
  id bigint generated by default as identity primary key,
  cup_id uuid not null references public.cups(id) on delete cascade,
  league_id uuid not null references public.leagues(id) on delete cascade,
  action text not null,
  actor_id uuid references auth.users(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default pg_catalog.now()
);

