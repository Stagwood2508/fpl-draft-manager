-- Server-owned gameweek lineup snapshots, deadline locking and repeat-safe autosubs.

create table if not exists public.gameweek_lineup_snapshots (
  id uuid primary key default gen_random_uuid(),
  league_id uuid not null references public.leagues(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  gameweek integer not null check (gameweek between 1 and 38),
  deadline_at timestamptz not null,
  starting_player_ids integer[] not null,
  bench_player_ids integer[] not null,
  effective_starting_player_ids integer[] not null,
  effective_bench_player_ids integer[] not null,
  status text not null default 'LOCKED' check (status in ('LOCKED', 'PROCESSED', 'CORRECTED')),
  captured_at timestamptz not null default now(),
  processed_at timestamptz,
  corrected_at timestamptz,
  corrected_by uuid references auth.users(id),
  correction_reason text,
  unique (league_id, user_id, gameweek)
);

create index if not exists gameweek_lineup_snapshots_lookup_idx
  on public.gameweek_lineup_snapshots(league_id, gameweek, user_id);

create table if not exists public.gameweek_autosub_audit (
  id bigint generated by default as identity primary key,
  snapshot_id uuid not null references public.gameweek_lineup_snapshots(id) on delete cascade,
  league_id uuid not null references public.leagues(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  gameweek integer not null,
  action_type text not null check (action_type in ('SWAP', 'SKIPPED', 'CORRECTION')),
  subbed_out_player_id integer references public.players(id),
  subbed_in_player_id integer references public.players(id),
  bench_priority integer,
  reason_code text not null,
  explanation text not null,
  created_at timestamptz not null default now()
);

create index if not exists gameweek_autosub_audit_lookup_idx
  on public.gameweek_autosub_audit(league_id, gameweek, user_id, created_at);

alter table public.gameweek_lineup_snapshots enable row level security;
alter table public.gameweek_autosub_audit enable row level security;

