create or replace function public.is_legal_starting_lineup(p_player_ids integer[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select cardinality(coalesce(p_player_ids, array[]::integer[])) = 11
    and count(distinct submitted.player_id) = 11
    and count(*) filter (where upper(p.element_type::text) in ('GKP', 'GK', '1')) = 1
    and count(*) filter (where upper(p.element_type::text) in ('DEF', '2')) between 3 and 5
    and count(*) filter (where upper(p.element_type::text) in ('MID', '3')) between 2 and 5
    and count(*) filter (where upper(p.element_type::text) in ('FWD', '4')) between 1 and 3
  from unnest(coalesce(p_player_ids, array[]::integer[])) submitted(player_id)
  join public.players p on p.id = submitted.player_id;
$$;

create or replace function public.refresh_league_gameweek_schedule()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  insert into public.league_gameweeks (
    league_id, gameweek, gw_deadline, waiver_deadline,
    is_current, is_finished, status, waiver_deadline_time
  )
  select
    l.id,
    g.gameweek_number,
    g.fpl_deadline_time,
    g.fpl_deadline_time - interval '24 hours',
    coalesce(g.is_current, false),
    coalesce(g.is_finished, false),
    case
      when coalesce(g.is_finished, false) then 'FINISHED'
      when pg_catalog.now() >= g.fpl_deadline_time then 'IN_PLAY'
      else 'WAIVERS_OPEN'
    end,
    g.fpl_deadline_time - interval '24 hours'
  from public.leagues l
  cross join public.gameweeks g
  where exists (
    select 1 from public.rosters r where r.league_id = l.id
  )
  on conflict (league_id, gameweek) do update
  set gw_deadline = excluded.gw_deadline,
      waiver_deadline = excluded.waiver_deadline,
      waiver_deadline_time = excluded.waiver_deadline_time,
      is_current = excluded.is_current,
      is_finished = excluded.is_finished,
      status = case
        when excluded.is_finished then 'FINISHED'
        when pg_catalog.now() >= excluded.gw_deadline then 'IN_PLAY'
        when public.league_gameweeks.status in ('FINISHED', 'IN_PLAY') then 'WAIVERS_OPEN'
        else public.league_gameweeks.status
      end;

  get diagnostics v_count = row_count;
  return jsonb_build_object('success', true, 'gameweeks_synchronised', v_count);
end;
$$;

create or replace function public.capture_due_gameweek_lineups(p_gameweek integer default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  perform public.refresh_league_gameweek_schedule();

  insert into public.gameweek_lineup_snapshots (
    league_id, user_id, gameweek, deadline_at,
    starting_player_ids, bench_player_ids,
    effective_starting_player_ids, effective_bench_player_ids
  )
  select
    r.league_id,
    r.user_id,
    lg.gameweek,
    lg.gw_deadline,
    array_agg(r.player_id order by r.player_id) filter (where r.is_starting),
    array_agg(r.player_id order by r.bench_order nulls last, r.player_id) filter (where not r.is_starting),
    array_agg(r.player_id order by r.player_id) filter (where r.is_starting),
    array_agg(r.player_id order by r.bench_order nulls last, r.player_id) filter (where not r.is_starting)
  from public.rosters r
  join public.league_gameweeks lg
    on lg.league_id = r.league_id
   and (p_gameweek is null or lg.gameweek = p_gameweek)
  where lg.gw_deadline <= pg_catalog.now()
  group by r.league_id, r.user_id, lg.gameweek, lg.gw_deadline
  having count(*) = 15
     and count(*) filter (where r.is_starting) = 11
     and count(*) filter (where not r.is_starting) = 4
  on conflict (league_id, user_id, gameweek) do nothing;

  get diagnostics v_count = row_count;
  return jsonb_build_object('success', true, 'snapshots_created', v_count);
end;
$$;

create or replace function public.process_gameweek_autosubs(
  p_league_id uuid,
  p_gameweek integer,
  p_force boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_snapshot record;
  v_effective integer[];
  v_candidate integer[];
  v_starting_gk integer;
  v_bench_gk integer;
  v_bench_player integer;
  v_bench_priority integer;
  v_absent_starter integer;
  v_swap_count integer := 0;
  v_skipped_count integer := 0;
  v_processed_count integer := 0;
  v_gameweek_finished boolean;
begin
  if auth.uid() is not null
     and not exists (
       select 1 from public.leagues l
       where l.id = p_league_id and l.commissioner_id = auth.uid()
     ) then
    return jsonb_build_object('success', false, 'error', 'COMMISSIONER_REQUIRED');
  end if;

  select coalesce(g.is_finished, false)
  into v_gameweek_finished
  from public.gameweeks g
  where g.gameweek_number = p_gameweek;

  if not coalesce(v_gameweek_finished, false) and not p_force then
    return jsonb_build_object('success', false, 'error', 'GAMEWEEK_IN_PROGRESS');
  end if;

  perform public.capture_due_gameweek_lineups(p_gameweek);

  for v_snapshot in
    select *
    from public.gameweek_lineup_snapshots s
    where s.league_id = p_league_id
      and s.gameweek = p_gameweek
      and s.status = 'LOCKED'
    for update
  loop
    v_effective := v_snapshot.starting_player_ids;

    select submitted.player_id into v_starting_gk
    from unnest(v_snapshot.starting_player_ids) submitted(player_id)
    join public.players p on p.id = submitted.player_id
    where upper(p.element_type::text) in ('GKP', 'GK', '1')
    limit 1;

    select submitted.player_id into v_bench_gk
    from unnest(v_snapshot.bench_player_ids) submitted(player_id)
    join public.players p on p.id = submitted.player_id
    where upper(p.element_type::text) in ('GKP', 'GK', '1')
    limit 1;

    if coalesce((select s.minutes from public.player_gameweek_stats s where s.player_id = v_starting_gk and s.gameweek = p_gameweek), 0) = 0 then
      if coalesce((select s.minutes from public.player_gameweek_stats s where s.player_id = v_bench_gk and s.gameweek = p_gameweek), 0) > 0 then
        v_effective := array_replace(v_effective, v_starting_gk, v_bench_gk);
        insert into public.gameweek_autosub_audit (
          snapshot_id, league_id, user_id, gameweek, action_type,
          subbed_out_player_id, subbed_in_player_id, bench_priority,
          reason_code, explanation
        ) values (
          v_snapshot.id, p_league_id, v_snapshot.user_id, p_gameweek, 'SWAP',
          v_starting_gk, v_bench_gk, 0,
          'GOALKEEPER_DID_NOT_PLAY',
          'The starting goalkeeper played 0 minutes, so the substitute goalkeeper was used.'
        );
        v_swap_count := v_swap_count + 1;
      else
        insert into public.gameweek_autosub_audit (
          snapshot_id, league_id, user_id, gameweek, action_type,
          subbed_out_player_id, bench_priority, reason_code, explanation
        ) values (
          v_snapshot.id, p_league_id, v_snapshot.user_id, p_gameweek, 'SKIPPED',
          v_starting_gk, 0, 'NO_GOALKEEPER_REPLACEMENT',
          'The starting goalkeeper played 0 minutes, but the substitute goalkeeper also did not play.'
        );
        v_skipped_count := v_skipped_count + 1;
      end if;
    end if;

    for v_bench_player, v_bench_priority in
      select submitted.player_id, (submitted.ordinality - 1)::integer
      from unnest(v_snapshot.bench_player_ids) with ordinality submitted(player_id, ordinality)
      join public.players p on p.id = submitted.player_id
      where upper(p.element_type::text) not in ('GKP', 'GK', '1')
        and coalesce((
          select s.minutes from public.player_gameweek_stats s
          where s.player_id = submitted.player_id and s.gameweek = p_gameweek
        ), 0) > 0
      order by submitted.ordinality
    loop
      v_absent_starter := null;

      for v_absent_starter in
        select effective.player_id
        from unnest(v_effective) with ordinality effective(player_id, ordinality)
        join public.players p on p.id = effective.player_id
        where upper(p.element_type::text) not in ('GKP', 'GK', '1')
          and coalesce((
            select s.minutes from public.player_gameweek_stats s
            where s.player_id = effective.player_id and s.gameweek = p_gameweek
          ), 0) = 0
        order by effective.ordinality
      loop
        v_candidate := array_replace(v_effective, v_absent_starter, v_bench_player);
        if public.is_legal_starting_lineup(v_candidate) then
          v_effective := v_candidate;
          insert into public.gameweek_autosub_audit (
            snapshot_id, league_id, user_id, gameweek, action_type,
            subbed_out_player_id, subbed_in_player_id, bench_priority,
            reason_code, explanation
          ) values (
            v_snapshot.id, p_league_id, v_snapshot.user_id, p_gameweek, 'SWAP',
            v_absent_starter, v_bench_player, v_bench_priority,
            'OUTFIELD_PLAYER_DID_NOT_PLAY',
            'A starting outfield player played 0 minutes. The highest-priority eligible substitute was used while preserving a legal formation.'
          );
          v_swap_count := v_swap_count + 1;
          exit;
        end if;
      end loop;
    end loop;

    for v_absent_starter in
      select effective.player_id
      from unnest(v_effective) effective(player_id)
      join public.players p on p.id = effective.player_id
      where upper(p.element_type::text) not in ('GKP', 'GK', '1')
        and coalesce((
          select s.minutes from public.player_gameweek_stats s
          where s.player_id = effective.player_id and s.gameweek = p_gameweek
        ), 0) = 0
    loop
      insert into public.gameweek_autosub_audit (
        snapshot_id, league_id, user_id, gameweek, action_type,
        subbed_out_player_id, reason_code, explanation
      ) values (
        v_snapshot.id, p_league_id, v_snapshot.user_id, p_gameweek, 'SKIPPED',
        v_absent_starter, 'NO_ELIGIBLE_SUBSTITUTE',
        'No playing substitute could replace this player without breaking the formation rules.'
      );
      v_skipped_count := v_skipped_count + 1;
    end loop;

    update public.gameweek_lineup_snapshots
    set effective_starting_player_ids = v_effective,
        effective_bench_player_ids = v_snapshot.bench_player_ids,
        status = 'PROCESSED',
        processed_at = pg_catalog.now()
    where id = v_snapshot.id;

    v_processed_count := v_processed_count + 1;
  end loop;

  return jsonb_build_object(
    'success', true,
    'league_id', p_league_id,
    'gameweek', p_gameweek,
    'lineups_processed', v_processed_count,
    'swaps', v_swap_count,
    'unresolved_absences', v_skipped_count
  );
end;
$$;

create or replace function public.process_due_gameweek_autosubs(p_gameweek integer default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league record;
  v_gameweek record;
  v_result jsonb;
  v_processed integer := 0;
begin
  perform public.refresh_league_gameweek_schedule();
  perform public.capture_due_gameweek_lineups(p_gameweek);

  for v_gameweek in
    select g.gameweek_number
    from public.gameweeks g
    where coalesce(g.is_finished, false)
      and (p_gameweek is null or g.gameweek_number = p_gameweek)
  loop
    for v_league in
      select distinct s.league_id
      from public.gameweek_lineup_snapshots s
      where s.gameweek = v_gameweek.gameweek_number and s.status = 'LOCKED'
    loop
      v_result := public.process_gameweek_autosubs(v_league.league_id, v_gameweek.gameweek_number, false);
      v_processed := v_processed + coalesce((v_result ->> 'lineups_processed')::integer, 0);
    end loop;
  end loop;

  return jsonb_build_object('success', true, 'lineups_processed', v_processed);
end;
$$;

