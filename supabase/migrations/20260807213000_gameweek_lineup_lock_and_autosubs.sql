create or replace function public.process_auto_subs(p_gameweek integer)
returns table(
  league_id uuid,
  roster_id uuid,
  subbed_out_player_id integer,
  subbed_in_player_id integer,
  sub_reason text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
