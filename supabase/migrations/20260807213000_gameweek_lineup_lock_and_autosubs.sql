-- The previous scheduler embedded a revoked legacy JWT. Read a dedicated cron
-- secret from Vault instead; the value is provisioned separately from source control.
create or replace function public.trigger_live_stats_sync()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current_gw integer;
  v_cron_secret text;
  v_request_id bigint;
begin
  select g.gameweek_number into v_current_gw
  from public.gameweeks g
  where coalesce(g.is_current, false)
  order by g.gameweek_number desc
  limit 1;

  if v_current_gw is null then
    select g.gameweek_number into v_current_gw
    from public.gameweeks g
    where not coalesce(g.is_finished, false)
    order by g.fpl_deadline_time
    limit 1;
  end if;

  v_current_gw := coalesce(v_current_gw, 1);

  select s.decrypted_secret into v_cron_secret
  from vault.decrypted_secrets s
  where s.name = 'live_stats_cron_secret'
  limit 1;

  if v_cron_secret is null then
    raise warning 'live_stats_cron_secret is not configured; live stats sync skipped';
    return;
  end if;

  select net.http_get(
    url := 'https://fnysbiwhwcqqqdwvhkau.supabase.co/functions/v1/sync-live-stats?gameweek=' || v_current_gw,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', v_cron_secret
    )
  ) into v_request_id;
end;
$$;

