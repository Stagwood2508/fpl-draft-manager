    on r.league_id = a.league_id
   and r.user_id = a.user_id
   and r.player_id = a.subbed_out_player_id
  where a.gameweek = p_gameweek and a.action_type = 'SWAP';
end;
$$;

create or replace function public.commissioner_correct_gameweek_lineup(
  p_league_id uuid,
  p_user_id uuid,
  p_gameweek integer,
  p_effective_starting_player_ids integer[],
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_snapshot public.gameweek_lineup_snapshots%rowtype;
begin
  if auth.uid() is null or not exists (
    select 1 from public.leagues l
    where l.id = p_league_id and l.commissioner_id = auth.uid()
  ) then
    return jsonb_build_object('success', false, 'error', 'COMMISSIONER_REQUIRED');
  end if;

  if nullif(trim(coalesce(p_reason, '')), '') is null then
    return jsonb_build_object('success', false, 'error', 'CORRECTION_REASON_REQUIRED');
  end if;

  select * into v_snapshot
  from public.gameweek_lineup_snapshots s
  where s.league_id = p_league_id and s.user_id = p_user_id and s.gameweek = p_gameweek
  for update;

  if not found then
    return jsonb_build_object('success', false, 'error', 'SNAPSHOT_NOT_FOUND');
  end if;

  if not public.is_legal_starting_lineup(p_effective_starting_player_ids)
     or exists (
       select 1 from unnest(p_effective_starting_player_ids) submitted(player_id)
       where not (submitted.player_id = any(v_snapshot.starting_player_ids || v_snapshot.bench_player_ids))
     ) then
    return jsonb_build_object('success', false, 'error', 'INVALID_CORRECTED_LINEUP');
  end if;

  update public.gameweek_lineup_snapshots
  set effective_starting_player_ids = p_effective_starting_player_ids,
      status = 'CORRECTED',
      corrected_at = pg_catalog.now(),
      corrected_by = auth.uid(),
      correction_reason = trim(p_reason)
  where id = v_snapshot.id;

  insert into public.gameweek_autosub_audit (
    snapshot_id, league_id, user_id, gameweek, action_type,
    reason_code, explanation
  ) values (
    v_snapshot.id, p_league_id, p_user_id, p_gameweek, 'CORRECTION',
    'COMMISSIONER_CORRECTION', trim(p_reason)
  );

  return jsonb_build_object('success', true, 'snapshot_id', v_snapshot.id);
end;
$$;

