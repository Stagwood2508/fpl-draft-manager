create or replace function public.save_manager_lineup(
  p_league_id uuid,
  p_starting_player_ids integer[],
  p_bench_player_ids integer[]
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_locked_gameweek integer;
begin
  select g.gameweek_number into v_locked_gameweek
  from public.gameweeks g
  where g.fpl_deadline_time <= pg_catalog.now()
    and not coalesce(g.is_finished, false)
  order by g.gameweek_number desc
  limit 1;

  if v_locked_gameweek is not null then
    perform public.capture_due_gameweek_lineups(v_locked_gameweek);
    return jsonb_build_object(
      'success', false,
      'error', 'LINEUP_LOCKED',
      'gameweek', v_locked_gameweek
    );
  end if;

  return public.save_manager_lineup_unlocked(
    p_league_id,
    p_starting_player_ids,
    p_bench_player_ids
  );
end;
$$;

