-- Queue draft waiting-room and start alerts through the existing in-app inbox.
-- The Edge Function webhook decides whether each inbox record also becomes push.
create or replace function public.enqueue_due_draft_notifications()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_waiting integer := 0; v_live integer := 0;
begin
  insert into public.user_notifications (
    user_id, league_id, category, title, body, route, dedupe_key
  )
  select member.user_id, settings.league_id, 'SYSTEM',
    'Draft waiting room is open',
    'Your draft starts in around 10 minutes. Ready up and review your watchlist.',
    '/draft-room?leagueId=' || settings.league_id,
    'draft-waiting:' || settings.league_id || ':' || extract(epoch from settings.draft_start_time)::bigint
  from public.league_settings settings
  join public.leagues league on league.id = settings.league_id
  join public.league_members member on member.league_id = settings.league_id
  left join public.notification_preferences preference on preference.user_id = member.user_id
  where settings.draft_start_time > pg_catalog.now()
    and settings.draft_start_time <= pg_catalog.now() + interval '10 minutes'
    and upper(coalesce(league.draft_status, league.status, 'PRE_DRAFT')) in ('PRE_DRAFT', 'WAITING_ROOM', 'NOT_STARTED', 'WAITING')
    and coalesce(preference.draft_enabled, true)
  on conflict (user_id, dedupe_key) where dedupe_key is not null do nothing;
  get diagnostics v_waiting = row_count;

  insert into public.user_notifications (
    user_id, league_id, category, title, body, route, dedupe_key
  )
  select member.user_id, settings.league_id, 'SYSTEM',
    'Your league draft is starting',
    'Enter the draft room now. The first manager will be on the clock.',
    '/draft-room?leagueId=' || settings.league_id,
    'draft-start:' || settings.league_id || ':' || extract(epoch from settings.draft_start_time)::bigint
  from public.league_settings settings
  join public.leagues league on league.id = settings.league_id
  join public.league_members member on member.league_id = settings.league_id
  left join public.notification_preferences preference on preference.user_id = member.user_id
  where settings.draft_start_time <= pg_catalog.now()
    and settings.draft_start_time > pg_catalog.now() - interval '30 minutes'
    and upper(coalesce(league.draft_status, league.status, 'PRE_DRAFT')) not in ('COMPLETED', 'FINISHED')
    and coalesce(preference.draft_enabled, true)
  on conflict (user_id, dedupe_key) where dedupe_key is not null do nothing;
  get diagnostics v_live = row_count;

  return jsonb_build_object('success', true, 'waiting_room_notifications', v_waiting, 'draft_start_notifications', v_live);
end;
$$;

revoke all on function public.enqueue_due_draft_notifications() from public, anon, authenticated;
grant execute on function public.enqueue_due_draft_notifications() to service_role;

do $$
declare v_job_id bigint;
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    for v_job_id in select jobid from cron.job where jobname = 'draft-push-notification-queue' loop
      perform cron.unschedule(v_job_id);
    end loop;
    perform cron.schedule(
      'draft-push-notification-queue',
      '* * * * *',
      'select public.enqueue_due_draft_notifications();'
    );
  end if;
end;
$$;
